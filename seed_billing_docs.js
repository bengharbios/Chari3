const { PrismaClient } = require('@prisma/client');
const prisma = new PrismaClient();

async function main() {
  // First, check if the doc already exists
  const existingDoc = await prisma.docArticle.findFirst({
    where: { slug: 'billing-and-addons-system' }
  });

  const content = `
# نظام الفوترة والاشتراكات والميزات الإضافية

تم تطوير نظام فوترة متكامل لمنصة ChariDay يتيح للمشرفين (Admins) التحكم الكامل في الباقات، الميزات الإضافية (Add-ons)، وعمولات المبيعات. في هذا المقال نشرح كيفية إدارة هذه الميزات وصلاحيات الوصول.

## 1. الباقات والاشتراكات (Packages & Subscriptions)
يتم تقسيم اشتراكات التجار إلى باقات (Packages)، وكل باقة تمنح التاجر مجموعة من الخصائص.
- **التجديد والانتهاء:** عند انتهاء اشتراك التاجر، يمكن للنظام تعليق المتجر تلقائياً أو إرجاعه إلى "الباقة الافتراضية" المجانية (Downgrade).
- **فترة السماح (Grace Period):** يمكن للمشرف تحديد فترة سماح للأيام بعد انتهاء الاشتراك قبل أن يتم حظر لوحة التحكم.
- **الفترة التجريبية (Trial):** يمكن تفعيل فترة تجريبية للمتاجر الجديدة تلقائياً عند التسجيل.

## 2. إدارة الميزات الإضافية (Add-ons)
الميزات الإضافية هي خدمات يمكن للتاجر شراؤها أو تفعيلها بشكل منفصل عن الباقة الأساسية. أمثلة على الميزات الإضافية:
- **تطبيق الموبايل (mobileApp):** إتاحة تطبيق جوال خاص بالمتجر.
- **الربط مع الواتساب (whatsapp):** تفعيل إشعارات الواتساب للطلبات.
- **نظام إدارة العملاء (crm):** أدوات متقدمة لإدارة علاقات العملاء.
- **نقاط البيع (pos):** تفعيل تطبيق نقاط البيع للمتاجر الفعلية.
- **نقاط بيع إضافية (extraPos):** شراء أجهزة أو حسابات POS إضافية.

### كيف أتحكم في الميزات الإضافية من لوحة الإدارة؟
1. قم بالدخول إلى لوحة المشرف العام (Super Admin).
2. من القائمة الجانبية، اذهب إلى **الفوترة والاشتراكات (Billing)** ثم **إعدادات المنصة (Settings)**.
3. في تلك الصفحة ستجد قسماً مخصصاً باسم **الميزات والخدمات الإضافية (Optional Add-ons)**.
4. من هناك يمكنك **إضافة ميزة جديدة**، تحديد سعرها، وإعطاؤها مفتاحاً برمجياً (مثلاً \`whatsapp\`).
5. بمجرد إضافتها، ستظهر للتجار في صفحة "الترقية" لشرائها.

## 3. الفرق بين التاجر ومدير المتجر (Seller vs Store Manager)
تم تحديث صلاحيات الوصول لفصل ملكية المتجر عن الإدارة اليومية:
- **التاجر (Seller):** هو المالك الحقيقي للمتجر. هو الوحيد الذي يمكنه ترقية الباقة، شراء الميزات الإضافية، وسحب الأرباح من المحفظة.
- **مدير المتجر (Store Manager):** هو موظف لدى التاجر (أو التاجر نفسه عند دخوله للوحة الإدارة اليومية). يتمتع بصلاحيات إضافة المنتجات وإدارة الطلبات، ولكنه **لا يستطيع** تعديل بيانات الدفع أو الباقات.

عندما يقوم التاجر بتعيين مدير متجر، فإن هذا المدير سيرى لوحة التحكم المتعلقة بالمبيعات، ولن تزعجه رسائل تجديد الاشتراك إلا إذا كان المتجر معلقاً بالكامل.
  `;

  if (existingDoc) {
    await prisma.docArticle.update({
      where: { id: existingDoc.id },
      data: {
        title: 'نظام الفوترة والميزات الإضافية وصلاحيات المتاجر',
        content: content,
        category: 'BILLING',
        isPublished: true,
        sortOrder: 20
      }
    });
    console.log('Updated existing billing documentation.');
  } else {
    await prisma.docArticle.create({
      data: {
        title: 'نظام الفوترة والميزات الإضافية وصلاحيات المتاجر',
        slug: 'billing-and-addons-system',
        content: content,
        category: 'BILLING',
        isPublished: true,
        sortOrder: 20
      }
    });
    console.log('Created new billing documentation.');
  }

}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
